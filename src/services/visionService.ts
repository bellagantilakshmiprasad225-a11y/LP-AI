import * as cocoSsd from '@tensorflow-models/coco-ssd';
import '@tensorflow/tfjs';

export interface DetectedObject {
  class: string;
  score: number;
  bbox: [number, number, number, number]; // [x, y, width, height]
}

let modelPromise: Promise<cocoSsd.ObjectDetection> | null = null;

export async function loadVisionModel(): Promise<cocoSsd.ObjectDetection> {
  if (!modelPromise) {
    modelPromise = cocoSsd.load({ base: 'lite_mobilenet_v2' });
  }
  return modelPromise;
}

export async function detectObjects(
  imageOrVideo: HTMLImageElement | HTMLVideoElement | HTMLCanvasElement
): Promise<DetectedObject[]> {
  const model = await loadVisionModel();
  const predictions = await model.detect(imageOrVideo);
  return predictions.map(p => ({
    class: p.class,
    score: p.score,
    bbox: p.bbox,
  }));
}

